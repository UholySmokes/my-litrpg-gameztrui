const buildDamageAbility = ({
  id,
  name,
  description,
  element,
  multiplier = 1.2,
  isMagic = true,
  cost = 25,
  cooldown = 6,
  effects = [],
  aoe = null,
  lifesteal,
  bonusVsTags,
  executeThreshold,
  heal,
  resourceGain,
  cleanse,
  summon,
  stealth,
  setEnrage,
  randomBuff,
  randomDebuff,
  setAbsorption,
}) => ({
  id,
  name,
  description,
  cost,
  costType: "mana",
  cooldown,
  target: "enemy",
  damage: { multiplier, isMagic, element },
  ...(effects.length ? { effects } : {}),
  ...(aoe ? { aoe } : {}),
  ...(Number.isFinite(lifesteal) ? { lifesteal } : {}),
  ...(bonusVsTags ? { bonusVsTags } : {}),
  ...(executeThreshold ? { executeThreshold } : {}),
  ...(heal ? { heal } : {}),
  ...(resourceGain ? { resourceGain } : {}),
  ...(cleanse ? { cleanse } : {}),
  ...(summon ? { summon } : {}),
  ...(stealth ? { stealth } : {}),
  ...(setEnrage ? { setEnrage } : {}),
  ...(randomBuff ? { randomBuff } : {}),
  ...(randomDebuff ? { randomDebuff } : {}),
  ...(setAbsorption ? { setAbsorption } : {}),
});

