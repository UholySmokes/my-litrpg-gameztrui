function buildConnectionsById() {
  const map = new Map(LANDMASS_DATA.map((entry) => [entry.id, new Set()]));
  CONNECTION_PAIRS.forEach(([left, right]) => {
    map.get(left)?.add(right);
    map.get(right)?.add(left);
  });
  return freezeObject(
    Object.fromEntries(
      Array.from(map.entries()).map(([id, targets]) => [id, freezeObject(Array.from(targets))]),
    ),
  );
}

