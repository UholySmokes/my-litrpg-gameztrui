export function resolveSquadProfileId(classRef) {
  const classId =
    typeof classRef === "string" ? classRef : classRef?.id || null;
  const lineage = getClassLineage(classId);
  const tierOne = lineage.find((entry) => entry?.tier === 1);
  const resolvedId = tierOne?.id || classId || "warrior";
  return SKIRMISH_SQUAD_PROFILES[resolvedId] ? resolvedId : "warrior";
}

export function getSquadProfileForClass(classRef) {
  return (
    SKIRMISH_SQUAD_PROFILES[resolveSquadProfileId(classRef)] ||
    SKIRMISH_SQUAD_PROFILES.warrior
  );
}
